// Package testdb gives each integration test its own freshly migrated
// database on the compose (or CI service) Postgres. Isolated databases let
// test packages run in parallel without truncating each other's tables.
package testdb

import (
	"context"
	"crypto/rand"
	"encoding/hex"
	"fmt"
	"net/url"
	"os"
	"testing"
	"time"

	"github.com/jackc/pgx/v5"
	"github.com/jackc/pgx/v5/pgxpool"

	"github.com/roymwxuk/mwx-go-flash-sale/internal/db"
)

const defaultURL = "postgres://flashsale:flashsale@localhost:5432/flashsale?sslmode=disable"

// New creates a database, migrates it, and drops it when the test ends.
// Integration tests are skipped under `go test -short`.
func New(t testing.TB, maxConns int32) *pgxpool.Pool {
	t.Helper()
	if testing.Short() {
		t.Skip("integration test: needs Postgres (run `make up`)")
	}

	baseURL := os.Getenv("DATABASE_URL")
	if baseURL == "" {
		baseURL = defaultURL
	}
	ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
	defer cancel()

	admin, err := pgx.Connect(ctx, baseURL)
	if err != nil {
		t.Fatalf("connect to Postgres at %s (did you run `make up`?): %v", baseURL, err)
	}
	defer admin.Close(ctx)

	name := "test_" + randomSuffix(t)
	// Identifiers cannot be bound as $1 parameters; name is generated by us.
	if _, err := admin.Exec(ctx, "CREATE DATABASE "+name); err != nil {
		t.Fatalf("create database: %v", err)
	}

	u, err := url.Parse(baseURL)
	if err != nil {
		t.Fatal(err)
	}
	u.Path = "/" + name

	pool, err := db.NewPool(ctx, u.String(), maxConns)
	if err != nil {
		t.Fatal(err)
	}
	if err := db.Migrate(ctx, pool); err != nil {
		pool.Close()
		t.Fatal(err)
	}

	t.Cleanup(func() {
		pool.Close()
		ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
		defer cancel()
		c, err := pgx.Connect(ctx, baseURL)
		if err != nil {
			t.Logf("cleanup connect: %v", err)
			return
		}
		defer c.Close(ctx)
		if _, err := c.Exec(ctx, fmt.Sprintf("DROP DATABASE IF EXISTS %s WITH (FORCE)", name)); err != nil {
			t.Logf("drop database %s: %v", name, err)
		}
	})
	return pool
}

func randomSuffix(t testing.TB) string {
	b := make([]byte, 6)
	if _, err := rand.Read(b); err != nil {
		t.Fatal(err)
	}
	return hex.EncodeToString(b)
}
